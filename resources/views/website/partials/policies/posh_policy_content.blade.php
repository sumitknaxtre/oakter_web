<h3 class="policy-heading policy-heading-gold">POLICY ON PREVENTION, PROHIBITION AND REDRESSAL OF SEXUAL HARASSMENT AT WORKPLACE</h3>
<h3 class="policy-heading policy-heading-teal">1. PRELIMINARY</h3>
<p>The policy to Prevent sexual harassment at workplace (“Policy”) is approved by the board of directors of Riot Labz Private Limited (“Oakter/Company”) on 30 October, 2019 and effective from 01 November 2019 and revised by the Board on 30th May, 2026 in the meeting of Board of Directors.</p>
<p>Oakter reserves the right to amend, abrogate, modify, rescind / reinstate the entire Policy or any part of it as and when required as per the notification, circulars, master circulars, rules issued by the Government of India time to time.</p>
<p>Oakter’s fundamental Policy is that we treat all the employees of Oakter with dignity and respect. Any act constituting a grievance or harassment of any employee, trainee, contractor, vendor, customer, contract employee on the basis of religion, caste, community, physical disability or any other reason is strictly prohibited. Avoidance of acts of harassment is a precondition of employment. This Policy is applicable to all those covered under Clause-3 of this Policy, irrespective of their religion, caste, creed, community, marital status, age, sexual orientation, gender identity, physical disability, or any other protected characteristic.</p>
<h3 class="policy-heading policy-heading-teal">2. OBJECTIVE</h3>
<p>Oakter is committed to providing a safe, secure and dignified workplace free from sexual harassment and discrimination to all women.</p>
<p>This Policy is framed in accordance with(a) The Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Act, 2013;</p>
<p class="policy-clause">(b) Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Rules, 2013;(c) The Repealing and Amending Act, 2016 and amendments thereto.</p>
<p>The Company adopts a zero-tolerance approach towards sexual harassment.</p>
<h3 class="policy-heading policy-heading-teal">3. SCOPE AND APPLICABILITY</h3>
<p>This Policy has been drafted keeping in view the provisions under “The Sexual Harassment of Women at Workplace (Prevention, Prohibition &amp; Redressal) Act, 2013 (“Act”) and this Policy applies to:</p>
<p class="policy-clause">1) All employees, regardless of seniority or contractual status, that is permanent, short-term contract, casual employees and trainees;</p>
<p class="policy-clause">2) All board members, executive and non-executive directors, owners, shareholders etc.;</p>
<p class="policy-clause">3) All contractors and sub-contractors;</p>
<p class="policy-clause">4) All persons dealing with Oakter, clients, customers, suppliers, vendors, applicants for employment and anyone with whom employees interact personally or by telephone, or by electronic communication, including written communication, website and emails;</p>
<p class="policy-clause">5) All business locations of Oakter including subsidiaries, associate companies etc;</p>
<p class="policy-clause">6) Any external location including all foreign countries visited by employee due to or during the course of their employment with Oakter such as business locations of other Companies/entities, guest houses, foreign trips, office parties etc. organized by Oakter.;</p>
<p class="policy-clause">7) Any mode of transport provided by Oakter (or a representative of Oakter) for undertaking a journey to and from the aforementioned locations.</p>
<h3 class="policy-heading policy-heading-teal">4. MEANING OF WORKPLACE</h3>
<p>For the purposes of this Policy, “Workplace” shall have the meaning assigned to it under the Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Act, 2013 (“POSH Act”) and shall include, without limitation, any place or location where an employee is present or required to be present in connection with or arising out of his/her employment with the Company.</p>
<p>For the purposes of this Policy, the Workplace shall include:</p>
<p class="policy-clause">(i) the registered office, corporate office, branch office, factory, warehouse, plant, unit or any other premises of the Company;</p>
<p class="policy-clause">(ii) any premises of a client, customer, vendor, contractor, consultant, business associate or other third party visited by an employee in connection with or during the course of employment;</p>
<p class="policy-clause">(iii) any place visited by an employee arising out of or during the course of employment, including business trips, official travel, conferences, seminars, meetings, training programmes, workshops, Company-sponsored events, off-site meetings and other official activities;</p>
<p class="policy-clause">(iv) transportation provided, arranged or authorised by the Company for undertaking any journey in connection with employment;</p>
<p class="policy-clause">(v) Company-provided accommodation, hotels, guest houses or other places of stay during official travel or assignments; and</p>
<p class="policy-clause">(vi) any other place or location, including a remote working location or work-from-home arrangement, where an employee performs duties or participates in activities connected with or arising out of employment, to the extent applicable under the POSH Act.</p>
<h3 class="policy-heading policy-heading-teal">4. DEFINITION OF SEXUAL HARASSMENT</h3>
<p>Sexual harassment is emotionally abusive and creates an unhealthy, unproductive atmosphere at the workplace. Sexual harassment includes such unwelcome sexually determined behavior, as physical contacts and advances, sexually colored remarks, showing pornography and sexual demands whether by words, gestures or actions. Such conduct can be humiliating and may constitute a health and safety problem. Sexual harassment includes such unwelcome sexually determined behavior (whether directly or by implication) as:</p>
<p class="policy-clause">(a) Physical contact and advances;</p>
<p class="policy-clause">(b) Demand or request for sexual favours;</p>
<p class="policy-clause">(c) Making sexually colored remarks;</p>
<p class="policy-clause">(d) Showing pornography;</p>
<p class="policy-clause">(e) Unwelcome sexual advances involving verbal, non-verbal, or physical conduct such as sexually colored remarks, jokes, letters, phone calls, e-mail, gestures, showing of pornography, lurid stares, physical contact or molestation, stalking, sounds, display of pictures, signs, verbal or non-verbal communication which offends the individuals sensibilities and affect her/his performance.</p>
<p class="policy-clause">(f) Eve teasing, innuendos and taunts, physical confinement against one’s will and likely to intrude upon one’s privacy;</p>
<p class="policy-clause">(g) Act or conduct by a person in authority which creates the environment at workplace hostile or intimidating to a person belonging to the other sex;</p>
<p class="policy-clause">(h) Conduct of such an act at workplace or outside in relation to an employee of Company or vice versa during the course of employment; and</p>
<p class="policy-clause">(i) any unwelcome gesture by an employee having sexual overtones.</p>
<p>Illustrative examples include:</p>
<ul class="policy-bullets">
<li>Inappropriate touching;</li>
<li>Unwanted messages or emails;</li>
<li>Lewd comments or jokes;</li>
<li>Displaying offensive material;</li>
<li>Repeated requests for dates;</li>
<li>Stalking;</li>
<li>Online harassment;</li>
<li>Sharing obscene content electronically;</li>
<li>Retaliation after refusal of sexual advances.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">5. INTERNAL COMMITTEE</h3>
<p>The Company shall constitute an Internal Committee ("IC") as required to take up the cases of sexual harassment and constituted under Section 4 of the Act and rules thereof.</p>
<p>Composition:</p>
<p class="policy-clause">(a) Presiding Officer – Senior woman employee;(b) Minimum two employee members committed to women's causes or possessing legal/social work knowledge;(c) One external member from NGO, association or person familiar with issues relating to sexual harassment.</p>
<p>At least one-half of the members shall be women.</p>
<p>Members shall hold office for a term not exceeding three (3) years form their nomination and appointment.</p>
