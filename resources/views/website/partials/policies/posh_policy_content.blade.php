<h3 class="policy-heading policy-heading-teal">6. COMPLAINT MECHANISM</h3>
<p>Any aggrieved woman who feels and is being sexually harassed directly or indirectly may submit a complaint of the alleged incident to any member of the Committee in writing/verbal with her signature within 3 months from the date of incident and/or in case of series of incidents within 3 months from the date of last incident.</p>
<p>The Internal Committee may extend the period by another three months for sufficient cause.</p>
<p>Assistance shall be provided where the complainant is unable to make a written complaint.</p>
<h3 class="policy-heading policy-heading-teal">7A. COMPLAINT THROUGH LOCAL COMMITTEE, NODAL OFFICER AND SHe-Box</h3>
<p class="policy-clause">(a) Where the complaint is against the Employer, Managing Director, Occupier, Director, or any person responsible for the management and control of the workplace, or where an Internal Committee has not been constituted, the aggrieved woman may file a complaint before the Local Committee constituted by the District Officer under the Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Act, 2013.</p>
<p class="policy-clause">(b) Employees may also approach the Nodal Officer designated by the District Administration for receipt and forwarding of complaints to the Local Committee in accordance with the Act and Rules.</p>
<p class="policy-clause">(c) An aggrieved woman may also lodge a complaint through the Sexual Harassment Electronic Box (SHe-Box) portal of the Ministry of Women and Child Development, Government of India. Complaints received through the SHe-Box portal shall be processed in accordance with the provisions of the Act, Rules and Government notifications issued from time to time.</p>
<p class="policy-clause">(d) The availability of SHe-Box shall not restrict the right of an aggrieved woman to directly approach the Internal Committee or Local Committee.</p>
<h3 class="policy-heading policy-heading-teal">7B. COMPLAINTS BY PERSONS ACTING ON BEHALF OF AGGRIEVED WOMAN</h3>
<p>Where the aggrieved woman is unable to make a complaint on account of physical incapacity, mental incapacity or death, a complaint may be filed by such persons as permitted under the Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Rules, 2013 including a relative, friend, co-worker, special educator, qualified psychologist, guardian, legal heir or any other person having knowledge of the incident and authorised under the applicable provisions of law.</p>
<h3 class="policy-heading policy-heading-teal">8. CONCILIATION</h3>
<p>The Company shall ensure before initiating inquiry, the Internal Committee may, at the request of the aggrieved woman, attempt conciliation. No monetary settlement shall be made the basis of conciliation.</p>
<p>Settlement terms shall be recorded and implemented by the Company.</p>
<h3 class="policy-heading policy-heading-teal">9. INQUIRY PROCEDURE</h3>
<p>The Company shall comply the following process of inquiry:</p>
<ul class="policy-bullets">
<li>Copy of complaint shall be served on respondent within seven working days.</li>
<li>Respondent shall submit reply within ten working days.</li>
<li>Principles of natural justice shall be followed.</li>
<li>Parties may produce evidence and witnesses.</li>
<li>Inquiry shall be completed within ninety days.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">10. INTERIM RELIEF</h3>
<p>During inquiry, the Internal Committee may recommend:</p>
<ul class="policy-bullets">
<li>Transfer of complainant or respondent;</li>
<li>Grant of leave up to three months to complainant;</li>
<li>Restriction on reporting relationship;</li>
<li>Any other suitable relief.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">11. INQUIRY REPORT</h3>
<p>The Internal Committee shall submit its report within ten days of completion of inquiry.</p>
<p>The employer shall act on recommendations within sixty days.</p>
<h3 class="policy-heading policy-heading-teal">12. DISCIPLINARY ACTION</h3>
<p>Where allegations are proved, disciplinary action may include:</p>
<ul class="policy-bullets">
<li>Written apology;</li>
<li>Warning;</li>
<li>Reprimand;</li>
<li>Counselling;</li>
<li>Withholding promotion;</li>
<li>Withholding increment;</li>
<li>Suspension;</li>
<li>Transfer;</li>
<li>Termination;</li>
<li>Any other action permissible under law.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">13. COMPENSATION</h3>
<p>While determining compensation, the Internal Committee shall consider:</p>
<ul class="policy-bullets">
<li>Mental trauma and emotional distress;</li>
<li>Medical expenses;</li>
<li>Loss of career opportunities;</li>
<li>Income and financial status of respondent;</li>
<li>Feasibility of lump sum or instalment payment.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">14. FALSE OR MALICIOUS COMPLAINTS</h3>
<p>Action may be recommended only where malicious intent is established after inquiry.</p>
<p>Mere inability to substantiate a complaint or provide adequate proof shall not attract action.</p>
<h3 class="policy-heading policy-heading-teal">14A. RECORD RETENTION</h3>
<p>The Company shall maintain records relating to complaints, inquiry proceedings, evidence, inquiry reports, recommendations, action taken reports, awareness programmes and annual reports in a secure and confidential manner.</p>
<p>Such records shall be preserved for a minimum period of seven (7) years from the date of closure of the complaint or for such longer period as may be required under applicable law, litigation requirements or directions of any authority.</p>
<h3 class="policy-heading policy-heading-teal">15. CONFIDENTIALITY</h3>
<p>The following shall remain confidential:</p>
<ul class="policy-bullets">
<li>Identity of complainant;</li>
<li>Identity of respondent;</li>
<li>Witnesses;</li>
<li>Inquiry proceedings;</li>
<li>Recommendations;</li>
<li>Action taken report.</li>
</ul>
<p>Any breach may invite disciplinary action.</p>
<h3 class="policy-heading policy-heading-teal">16. PROTECTION AGAINST RETALIATION</h3>
<p>Any act of retaliation, victimisation, intimidation or adverse employment action against the complainant, respondent, witness or any person participating in the inquiry process shall be treated as misconduct and may attract disciplinary action.</p>
<h3 class="policy-heading policy-heading-teal">17. RESPONSIBILITIES OF EMPLOYER</h3>
<p>The Company shall:</p>
<ul class="policy-bullets">
<li>Provide a safe workplace;</li>
<li>Display POSH awareness notices;</li>
<li>Organise awareness programmes;</li>
<li>Conduct IC training programmes;</li>
<li>Assist IC in inquiry;</li>
<li>Assist complainants in criminal proceedings;</li>
<li>File statutory disclosures and annual reports.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">17A. DUTIES OF EMPLOYEES</h3>
<p>In order to maintain and promote Oakter's ethical values, every employee shall adhere to the following duties and responsibilities</p>
<ul class="policy-bullets">
<li>Maintain a respectful and dignified work environment;</li>
<li>Refrain from engaging in any act constituting sexual harassment;</li>
<li>Cooperate with the Internal Committee during inquiry proceedings;</li>
<li>Maintain confidentiality of complaints and inquiry proceedings;</li>
<li>Participate in awareness and training programmes conducted by the Company.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">18. ANNUAL REPORT</h3>
<p>The Internal Committee shall prepare and submit annual report containing:</p>
<ul class="policy-bullets">
<li>Number of complaints received;</li>
<li>Number disposed of;</li>
<li>Cases pending beyond ninety days;</li>
<li>Awareness programmes conducted;</li>
<li>Nature of action taken.</li>
</ul>
<h3 class="policy-heading policy-heading-teal">19. APPEAL</h3>
<p>Any person aggrieved by the recommendations of the Internal Committee or the implementation thereof may prefer an appeal within ninety (90) days before the authority prescribed under the applicable service rules or any law for the time being in force.</p>
<h3 class="policy-heading policy-heading-teal">20. REVIEW OF POLICY</h3>
<p>The Company reserves the right to amend this Policy to ensure compliance with applicable laws.</p>
<h3 class="policy-heading policy-heading-teal">21. AMENDMENTS</h3>
<p>The Company reserves the right to amend the Policy from time to time in order to comply with any laws / rules / regulations that come into effect from time to time, related to Sexual Harassment.</p>
