<h3 class="policy-heading policy-heading-teal">23. PROVISIONS OF BHARATIYA NYAYA SANHITA, 2023 RELATING TO SEXUAL HARASSMENT</h3>
<p>Under Bharatiya Nyaya Sanhita, 2023 Section 75 which deals with the Sexual Harassment has made this a “cognizable offense” i.e. a person charged with Sexual Harassment may be arrested without warrant.</p>
<p>Under Section 75 of the BNS, a person committing any of the following acts may be guilty of sexual harassment:</p>
<ul class="policy-bullets">
<li>Physical contact and advances involving unwelcome and explicit sexual overtures;</li>
<li>Demand or request for sexual favours;</li>
<li>Showing pornography against the will of a woman;</li>
<li>Making sexually coloured remarks.</li>
</ul>
<p>A person committing the above acts shall be liable for punishment as prescribed under the BNS.</p>
<p>In addition to Section 75 of the BNS, acts of sexual harassment may also constitute offences under:</p>
<ul class="policy-bullets">
<li>Section 74 – Assault or criminal force to woman with intent to outrage her modesty;</li>
<li>Section 77 – Voyeurism;</li>
<li>Section 78 – Stalking;</li>
<li>Section 63 – Definition of Rape;</li>
<li>Section 64 and related provisions – Punishment for Rape and aggravated forms of rape;</li>
<li>Section 79 – Word, gesture or act intended to insult modesty of a woman.</li>
</ul>
<p>Where the alleged conduct constitutes a criminal offence under applicable law, the aggrieved woman may, in addition to seeking redressal under this Policy, pursue remedies before the appropriate law enforcement authorities. The Internal Committee shall assist the aggrieved woman in filing a complaint with the police, wherever requested or required under applicable law.</p>
